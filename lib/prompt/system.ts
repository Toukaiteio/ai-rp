/** 场景状态为空时也要占位，保证回合层的结构每轮一致。 */
export const SCENE_UNKNOWN = "（未标注，按最近的对话判断）";

/**
 * 拼回合层的可变部分。
 *
   * 顺序固定：语言锁定 → 当前场景 → 剧情线 → 回合模式 → 输出要求。
 * 全部是「这一轮」的信息，随玩家输入变化，所以整段放在历史之后，
 * 既不会打断前缀缓存，也不会被长历史冲淡。
 *
 * 场景状态有两种来源：完整的 SceneState（每轮更新、带可信度），
 * 或者只有一句话的旧式 scene 字符串。两者都支持，前者优先。
 */
export function buildTurnLayer(input: {
  language: string;
  scene: string;
  /** 结构化的场景状态。给了就用它，忽略 scene。 */
  sceneState?: string;
  /**
   * 状态里没有地点时补一句角色卡的场景。
   * 状态只记「变化」，地点没变就不会出现在状态里；不补这一句，
   * 模型会以为「现在在哪儿」没有交代。
   */
  sceneFallback?: string;
  threads: string[];
  /**
   * 剧情线的详细版（含 summary 和挑选说明）。给了就用它替掉上面那行标题列表，
   * 免得同一批线在一段提示里出现两次。
   */
  threadDetail?: string;
  mode: string;
}): string {
  const blocks: string[] = [];

  // 顺序照 Phase 3 的约定：语言 → 场景状态 → 剧情线 → 回合模式 → 输出要求
  blocks.push(input.language);

  const stateLines = [
    "本轮状态：",
    input.sceneState
      ? `当前场景：\n${input.sceneState}${
          input.sceneFallback?.trim()
            ? `\n- 角色卡设定里的场景（状态里还没记地点，以它为准）：${input.sceneFallback.trim()}`
            : ""
        }`
      : `- 当前场景：${input.scene.trim() || SCENE_UNKNOWN}`,
    input.threadDetail?.trim()
      ? input.threadDetail.trim()
      : input.threads.length > 0
        ? `- 未完成的剧情线：${input.threads.join("；")}`
        : "",
  ].filter(Boolean);
  blocks.push(stateLines.join("\n"));

  blocks.push(input.mode);
  blocks.push(TURN_RULES);

  return blocks.join("\n\n");
}

